"use client";
import { useState } from "react";
import { FileDown, Link2, Check } from "lucide-react";
import { Button } from "@/components/ui/button";
import { computeTotals } from "@/lib/estimates/calc";
import type { EstimateDocData } from "./estimate-doc";

export function EstimatePdfButton({ e, appName }: { e: EstimateDocData; appName: string }) {
  const [busy, setBusy] = useState(false);
  async function download() {
    setBusy(true);
    try {
      const { jsPDF } = await import("jspdf");
      const { default: autoTable } = await import("jspdf-autotable");
      const t = computeTotals(e.lines, { taxRate: e.tax_rate, taxParts: e.tax_parts, taxLabor: e.tax_labor });
      const money = (n: number) => `$${n.toFixed(2)}`;
      const doc = new jsPDF({ unit: "pt", format: "letter" });
      doc.setFontSize(16);
      doc.text(e.shop?.name ?? "Estimate", 40, 50);
      doc.setFontSize(10);
      doc.setTextColor(90);
      const shopLines = [e.shop?.address, [e.shop?.phone, e.shop?.email].filter(Boolean).join(" · ")].filter(Boolean) as string[];
      shopLines.forEach((l, i) => doc.text(l, 40, 66 + i * 13));
      doc.setTextColor(0);
      doc.setFontSize(12);
      doc.text(`Estimate #${e.estimate_number}`, 572, 50, { align: "right" });
      doc.setFontSize(10);
      doc.setTextColor(90);
      doc.text(new Date(e.created_at).toLocaleDateString(), 572, 66, { align: "right" });
      if (e.valid_until) doc.text(`Valid until ${new Date(e.valid_until).toLocaleDateString()}`, 572, 79, { align: "right" });
      doc.setTextColor(0);
      let y = 110;
      doc.setFontSize(9);
      doc.setTextColor(120);
      doc.text("CUSTOMER", 40, y);
      doc.text("VEHICLE", 320, y);
      doc.setTextColor(0);
      doc.setFontSize(10);
      doc.text(e.customer_name ?? "—", 40, y + 14);
      doc.text([e.customer_phone, e.customer_email].filter(Boolean).join(" · ") || " ", 40, y + 27);
      if (e.vehicle) {
        doc.text(`${e.vehicle.year} ${e.vehicle.make} ${e.vehicle.model}${e.vehicle.engine ? " · " + e.vehicle.engine : ""}`, 320, y + 14);
        doc.text([e.vehicle.vin, e.vehicle.plate, e.vehicle.mileage ? `${e.vehicle.mileage.toLocaleString()} mi` : null].filter(Boolean).join(" · ") || " ", 320, y + 27);
      }
      y += 50;
      autoTable(doc, {
        startY: y,
        head: [["Item", "Qty / Hrs", "Rate", "Amount"]],
        body: e.lines.map((l, i) => [
          `${l.kind.toUpperCase()}  ${l.description}${l.part_number ? `  (${l.part_number})` : ""}`,
          l.kind === "labor" ? `${l.hours ?? 0} h` : String(l.quantity),
          money(l.unit_price),
          money(t.lines[i].amount),
        ]),
        styles: { fontSize: 9, cellPadding: 5 },
        headStyles: { fillColor: [30, 30, 36] },
        columnStyles: { 1: { halign: "right" }, 2: { halign: "right" }, 3: { halign: "right" } },
        margin: { left: 40, right: 40 },
      });
      const after = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14;
      const rows: [string, string][] = [
        ["Parts", money(t.parts)],
        ["Labor", money(t.labor)],
        ...(t.fees > 0 ? ([["Fees", money(t.fees)]] as [string, string][]) : []),
        [`Tax (${(e.tax_rate * 100).toFixed(2).replace(/\.?0+$/, "")}%)`, money(t.tax)],
        ["Total", money(t.total)],
      ];
      rows.forEach(([k, v], i) => {
        const yy = after + i * 14;
        if (k === "Total") doc.setFont("helvetica", "bold");
        doc.text(k, 440, yy);
        doc.text(v, 572, yy, { align: "right" });
        doc.setFont("helvetica", "normal");
      });
      let ny = after + rows.length * 14 + 20;
      if (e.notes) {
        doc.setFontSize(9);
        const wrapped = doc.splitTextToSize(e.notes, 532);
        doc.text(wrapped, 40, ny);
        ny += wrapped.length * 11 + 10;
      }
      doc.setFontSize(8);
      doc.setTextColor(120);
      doc.text(doc.splitTextToSize("This estimate is not a final invoice. Additional diagnosis may change parts and labor; you will be contacted for authorization before additional work.", 532), 40, ny);
      doc.text(`Generated by ${appName}`, 40, 760);
      doc.save(`estimate-${e.estimate_number}.pdf`);
    } finally {
      setBusy(false);
    }
  }
  return (
    <Button variant="outline" onClick={download} disabled={busy}>
      <FileDown /> PDF
    </Button>
  );
}

export function CopyShareLink({ url }: { url: string }) {
  const [copied, setCopied] = useState(false);
  return (
    <Button
      variant="outline"
      onClick={async () => {
        try {
          if (navigator.share) await navigator.share({ title: "Estimate", url });
          else {
            await navigator.clipboard.writeText(url);
            setCopied(true);
            setTimeout(() => setCopied(false), 2000);
          }
        } catch {
          /* cancelled */
        }
      }}
    >
      {copied ? <Check /> : <Link2 />} {copied ? "Copied" : "Share link"}
    </Button>
  );
}
